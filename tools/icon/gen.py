"""Generates Yomiage's launcher icons: a brushed vermilion ensō around a Mincho kanji, as Android
vector drawables, plus SVG/PNG previews. Usage: python3 gen.py <res dir> <preview dir>"""
import math
import sys

from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTCollection

RES, PREVIEW = sys.argv[1], sys.argv[2]
FONT = TTCollection('/usr/share/fonts/opentype/noto/NotoSerifCJK-Bold.ttc').fonts[0]  # JP

VERMILION = '#D8462B'
WASHI = '#F2EADB'
BG_IN, BG_OUT = '#272B38', '#0C0D12'


def smooth(a, b, x):
    t = min(1.0, max(0.0, (x - a) / (b - a)))
    return t * t * (3 - 2 * t)


def f(v):
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def enso_paths(cx=54.0, cy=54.0):
    """The ensō as filled polygons: a solid body, then bristle streaks that part as the ink runs dry."""
    t0 = math.radians(-62)
    sweep = math.radians(318)

    def width(u):
        press = 0.86 + 0.14 * smooth(0.0, 0.08, u)
        taper = 1 - 0.7 * smooth(0.5, 1.0, u)
        wobble = 1 + 0.06 * math.sin(u * 17.0)
        return 8.6 * press * taper * wobble

    def radius(u):
        return 26.0 + 0.9 * math.sin(2 * math.pi * 1.2 * u + 0.6) - 1.6 * smooth(0.72, 1.0, u)

    def point(u, d):
        th = t0 + sweep * u
        r = radius(u) + d
        return cx + r * math.cos(th), cy + r * math.sin(th)

    def band(u0, u1, lo, hi, steps):
        """Polygon between offsets lo(u)..hi(u) from the centre line, for u0..u1."""
        us = [u0 + (u1 - u0) * i / steps for i in range(steps + 1)]
        outer = [point(u, hi(u)) for u in us]
        inner = [point(u, lo(u)) for u in reversed(us)]
        pts = outer + inner
        return 'M' + 'L'.join(f'{f(x)},{f(y)}' for x, y in pts) + 'Z'

    paths = []
    # Solid body (with a rounded press at the start).
    paths.append(band(0.0, 0.62, lambda u: -width(u) / 2, lambda u: width(u) / 2, 140))
    sx, sy = point(0.0, 0.0)
    r0 = width(0.0) / 2
    paths.append(f'M{f(sx - r0)},{f(sy)}a{f(r0)},{f(r0)} 0,1 1,{f(2 * r0)},0a{f(r0)},{f(r0)} 0,1 1,{f(-2 * r0)},0Z')
    # Dry-brush streaks for the tail.
    n = 5
    ends = [1.0, 0.93, 0.975, 0.87, 0.95]
    for k in range(n):
        end = ends[k]

        def lo(u, k=k, end=end):
            w = width(u)
            gap = 0.6 * smooth(0.6, 0.95, u) * (w / n) / 2
            tip = 1 - smooth(end - 0.07, end, u)
            mid = -w / 2 + (k + 0.5) * w / n
            half = ((w / n) / 2 - gap) * tip
            return mid - max(half, 0.0)

        def hi(u, k=k, end=end):
            w = width(u)
            gap = 0.6 * smooth(0.6, 0.95, u) * (w / n) / 2
            tip = 1 - smooth(end - 0.07, end, u)
            mid = -w / 2 + (k + 0.5) * w / n
            half = ((w / n) / 2 - gap) * tip
            return mid + max(half, 0.0)

        paths.append(band(0.58, end, lo, hi, 90))
    return paths


def glyph_path(ch, size=29.0, cx=54.0, cy=54.5):
    """The kanji as a path, centred in the circle (fonts are y-up; icons are y-down)."""
    gs = FONT.getGlyphSet()
    name = FONT.getBestCmap()[ord(ch)]
    bp = BoundsPen(gs)
    gs[name].draw(bp)
    x0, y0, x1, y1 = bp.bounds
    s = size / max(x1 - x0, y1 - y0)
    gx, gy = (x0 + x1) / 2, (y0 + y1) / 2
    pen = SVGPathPen(gs, ntos=lambda v: f(v))
    # x' = s*(x - gx) + cx ; y' = -s*(y - gy) + cy
    tp = TransformPen(pen, (s, 0, 0, -s, cx - s * gx, cy + s * gy))
    gs[name].draw(tp)
    return pen.getCommands()


def vector(paths, colors):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- Generated by tools/icon: a brushed ensō around a Mincho kanji. -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="108dp"', '    android:height="108dp"',
           '    android:viewportWidth="108"', '    android:viewportHeight="108">']
    for p, c in zip(paths, colors):
        out.append(f'    <path android:fillColor="{c}" android:pathData="{p}" />')
    out.append('</vector>')
    return '\n'.join(out) + '\n'


def background_xml():
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!-- Deep indigo ink, a little lighter in the middle. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108h-108z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="radial"
                android:centerX="54"
                android:centerY="48"
                android:gradientRadius="76"
                android:startColor="#FF{BG_IN[1:]}"
                android:endColor="#FF{BG_OUT[1:]}" />
        </aapt:attr>
    </path>
</vector>
'''


def svg(paths, colors, size=512, mask='squircle'):
    body = '\n'.join(f'<path fill="{c}" d="{p}"/>' for p, c in zip(paths, colors))
    tf = 'transform="translate(18,18) scale(0.6667)"'
    clip = (f'<circle {tf} cx="54" cy="54" r="54"/>' if mask == 'circle' else
            f'<path {tf} d="M54,0C10,0 0,10 0,54S10,108 54,108 108,98 108,54 98,0 54,0Z"/>')
    return f'''<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="18 18 72 72">
<defs><radialGradient id="g" cx="54" cy="48" r="76" gradientUnits="userSpaceOnUse">
<stop offset="0" stop-color="{BG_IN}"/><stop offset="1" stop-color="{BG_OUT}"/></radialGradient>
<clipPath id="m">{clip}</clipPath></defs>
<g clip-path="url(#m)"><rect x="0" y="0" width="108" height="108" fill="url(#g)"/>
{body}</g></svg>'''


enso = enso_paths()
icons = {
    'ic_launcher_foreground': '読',
    'ic_read_screen_foreground': '画',
    'ic_tap_screen_foreground': '指',
}
for name, ch in icons.items():
    g = glyph_path(ch)
    paths = enso + [g]
    colors = ['#FF' + VERMILION[1:]] * len(enso) + ['#FF' + WASHI[1:]]
    open(f'{RES}/drawable/{name}.xml', 'w').write(vector(paths, colors))
    open(f'{PREVIEW}/{name}.svg', 'w').write(svg(paths, [VERMILION] * len(enso) + [WASHI]))
# Themed (monochrome) icon: the same shapes in one color.
mono_paths = enso + [glyph_path('読')]
open(f'{RES}/drawable/ic_launcher_mono.xml', 'w').write(vector(mono_paths, ['#FFFFFFFF'] * len(mono_paths)))
open(f'{RES}/drawable/ic_launcher_bg.xml', 'w').write(background_xml())
print('ok')
